import json, re, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); from stories_src import S, FILMS, AUD
ROOT = os.path.abspath(os.path.join(HERE, '..', '..')) + '/'
SPK = {'Madar': 'مادر', 'Baba': 'پدر', 'Ravi': 'راوی', 'Darya': 'دریا', 'Baran': 'باران'}
OUT = ROOT + 'docs/video/'
FA = str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')
PAUSE = {'short pause': .25, 'medium pause': .5, 'long pause': 1.0, 'sigh': .7, 'laughing': .9, 'whispering': 0, 'shouting': 0}
def dur(x):
    t = sum(PAUSE.get(m, 0) for m in re.findall(r'\[([^\]]+)\]', x)); c = re.sub(r'\[[^\]]+\]', '', x)
    return t + len(c.split()) / 2.7 + c.count('...') * .3 + len(re.findall(r'[.!؟?؛:]', c)) * .08
def tc(t): m = int(t // 60); return f'{m:02d}:{t - 60*m:04.1f}'
films, studio = {}, []
for n, (fid, f) in enumerate(FILMS.items(), 6):
    t, rows = 0.0, []
    for title, mood, lines, v in f['plans']:
        rows.append((round(t, 1), title, mood, lines, v)); t += sum(dur(x) + .22 for _, x in lines) + .15
    end = round(t + .4, 1); slug = f'{n:02d}-story-{fid}'; d = OUT + slug + '/'; os.makedirs(d, exist_ok=True)
    # real timings from the timecoder (paste its output into timings.txt): [mm:ss.s] per plan + the last one = end
    if os.path.exists(d + 'timings.txt'):
        ts = [int(m) * 60 + float(sec) for m, sec in re.findall(r'\[(\d+):(\d+(?:\.\d+)?)\]', open(d + 'timings.txt', encoding='utf-8').read())]
        if len(ts) == len(rows) + 1: rows = [(round(ts[i], 2),) + r[1:] for i, r in enumerate(rows)]; end = round(ts[-1], 2)
        else: print('!! timings.txt for', slug, 'has', len(ts), 'codes; expected', len(rows) + 1)
    vo = '\n'.join(f'- {k} ({SPK.get(k, k)}): صدای **{a}** – {b}' for k, (a, b) in f['voices'].items())
    mode = 'تک‌گوینده (Single-speaker audio)' if len(f['voices']) == 1 else 'دوگوینده (Multi-speaker audio)'
    md = f"# فیلم قصه: {f['title']}\n\nحالت AI Studio: {mode}\n\nگوینده‌ها:\n{vo}\n\nنسخه‌ی تایم‌کددار – {len(rows)} پلان، {len(rows)+1} تایم‌کد (آخری = پایان). تخمینی؛ با تایم‌کدزن اصلاح می‌شود.\n\n"
    for i, (s, title, mood, lines, v) in enumerate(rows, 1):
        md += f'[{tc(s)}] پلان {str(i).translate(FA)} – {title}\n' + '\n'.join(f'{k}: {x}' for k, x in lines) + '\n\n'
    md += f'[{tc(end)}] پایان\n'
    open(d + 'timecoded.md', 'w', encoding='utf-8').write(md)
    script = '\n'.join(f'{k}: {x}' for r in rows for k, x in r[3])
    if len(f['voices']) == 1: script = '\n'.join(re.sub(r'^\w+: ', '', l) for l in script.split('\n'))
    open(d + 'ai-studio.txt', 'w', encoding='utf-8').write("===== بخش ۱: در کادر Style instructions بچسبان =====\n\n" + f['style'] + "\n\n===== بخش ۲: در کادر متن (Script) بچسبان =====\n\n" + script + '\n')
    open(d + 'ai-studio-one-box.txt', 'w', encoding='utf-8').write(f['style'] + '\n\n' + script + '\n')
    films[fid] = {'end': end, 'spk': {k: SPK.get(k, k) for k in f['voices']}, 'voice': any(os.path.exists(d + 'voice.' + e) for e in ('wav', 'mp3', 'm4a')), 'plans': [{'t': s, 'title': ti, 'mood': mo, 'v': v, 'lines': [{'s': k, 'x': x} for k, x in li]} for s, ti, mo, li, v in rows]}
    if os.path.exists(ROOT + f'landing/stories/video/{fid}.mp4'): films[fid]['mp4'] = f'/stories/video/{fid}.mp4'
    if os.path.exists(ROOT + f'landing/stories/audio/{fid}.mp3'): films[fid]['audio'] = f'/stories/audio/{fid}.mp3'
    studio.append({'slug': slug, 'title': 'قصه: ' + f['title'], 'spk': films[fid]['spk'], 'end': end, 'plans': [{'t': p['t'], 'title': p['title'], 'mood': p['mood'], 'lines': p['lines']} for p in films[fid]['plans']]})
    print(slug, end, 'sec')
js = '/* generated by docs/video sources — do not edit by hand */\nwindow.STORY_AUD = ' + json.dumps(AUD, ensure_ascii=False) + ';\nwindow.STORIES = ' + json.dumps(S, ensure_ascii=False) + ';\nwindow.STORY_FILMS = ' + json.dumps(films, ensure_ascii=False) + ';\n'
open(ROOT + 'landing/assets/stories-data.js', 'w', encoding='utf-8').write(js)
if os.path.exists(HERE + '/studio.json'):
    base = json.load(open(HERE + '/studio.json', encoding='utf-8')); base = [v for v in base if not v['slug'].startswith(('06-', '07-', '08-'))] + studio
    json.dump(base, open(HERE + '/studio.json', 'w', encoding='utf-8'), ensure_ascii=False)
print(len(S), 'stories')
